// Run with a Playwright Page and Vite; reuses the filesystem fixture.
export default async function(page, origin='http://127.0.0.1:5173') {
 const assert=(value,message)=>{if(!value)throw new Error(message)}
 const frame=()=>page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))
 const checks=[]
 await page.setViewportSize({width:1100,height:760})
 await page.goto(origin+'/tests/marquee-selection.html')
 await page.waitForFunction(()=>window.marqueeFixture)
 const area=page.locator('.table-scroll'),bar=area.locator(':scope>.os-scrollbar-vertical'),handle=bar.locator('.os-scrollbar-handle')
 const geometry=()=>area.evaluate(el=>({width:el.clientWidth,height:el.clientHeight,row:el.querySelector('tbody tr').getBoundingClientRect().width,gutter:el.offsetWidth-el.clientWidth}))
 const before=await geometry()
 assert(before.gutter===0,'纵向滚动条占用了布局宽度')
 await page.waitForFunction(()=>getComputedStyle(document.querySelector('.table-scroll>.os-scrollbar-vertical')).opacity==='0')
 assert(await handle.evaluate(el=>getComputedStyle(el).pointerEvents==='none'),'透明滑块仍拦截点击')
 const bounds=await area.boundingBox()
 await page.mouse.move(bounds.x+bounds.width/2,bounds.y+100)
 await page.waitForFunction(()=>getComputedStyle(document.querySelector('.table-scroll>.os-scrollbar-vertical')).opacity==='1')
 const normal=await handle.evaluate(el=>getComputedStyle(el).backgroundColor)
 assert(await handle.evaluate(el=>el.getBoundingClientRect().width)===6,'滑块不是 6px')
 const handleBox=await handle.boundingBox()
 await page.mouse.move(handleBox.x+handleBox.width/2,handleBox.y+handleBox.height/2)
 await frame()
 const hover=await handle.evaluate(el=>getComputedStyle(el).backgroundColor)
 assert(normal!==hover,'悬停滑块未加深')
 await page.waitForTimeout(1200)
 assert(await bar.evaluate(el=>getComputedStyle(el).opacity==='1'),'悬停滑块时提前隐藏')
 await page.mouse.down()
 await frame()
 assert(await handle.evaluate(el=>getComputedStyle(el).backgroundColor)!==hover,'拖动时未进一步加深')
 await page.mouse.move(handleBox.x+handleBox.width/2,handleBox.y+150,{steps:8})
 await page.mouse.up();await frame()
 assert(await area.evaluate(el=>el.scrollTop>300),'拖动纵向滑块未滚动')
 assert(await page.evaluate(()=>!window.marqueeFixture.state.selected.length&&!document.querySelector('.selection-marquee,.file-drag-preview')),'拖动滑块触发了文件选择或文件拖拽')
 assert(await area.evaluate(el=>Math.abs(el.querySelector('thead').getBoundingClientRect().top-el.getBoundingClientRect().top)<1),'吸顶表头失效')
 await page.mouse.move(bounds.x+bounds.width/2,bounds.y+100)
 await page.waitForFunction(()=>getComputedStyle(document.querySelector('.table-scroll>.os-scrollbar-vertical')).opacity==='0')
 assert(JSON.stringify(await geometry())===JSON.stringify(before),'显隐或滚动时内容宽高发生变化')
 await page.mouse.wheel(0,200);await page.waitForFunction(()=>getComputedStyle(document.querySelector('.table-scroll>.os-scrollbar-vertical')).opacity==='1')
 checks.push('6px 纵向滑块、零占位、初始透明、移动/滚动显现、悬停/拖动加深、悬停保持、空闲隐藏、表头吸顶及无误选')

 await page.evaluate(()=>window.marqueeFixture.state.splitPane());await frame()
 const workspace=page.locator('.browser-content')
 assert(await workspace.evaluate(el=>el.scrollWidth>el.clientWidth&&el.offsetHeight===el.clientHeight),'分屏横向溢出或零占位失效')
 const workBox=await workspace.boundingBox()
 await page.mouse.move(workBox.x+50,workBox.y+workBox.height-5)
 const horizontal=workspace.locator(':scope>.os-scrollbar-horizontal .os-scrollbar-handle')
 await horizontal.waitFor({state:'visible'})
 const hbox=await horizontal.boundingBox()
 await page.mouse.move(hbox.x+hbox.width/2,hbox.y+hbox.height/2);await page.mouse.down()
 await page.mouse.move(hbox.x+hbox.width/2+60,hbox.y+hbox.height/2,{steps:8});await page.mouse.up();await frame()
 assert(await workspace.evaluate(el=>el.scrollLeft>0),'横向滑块不能拖动')
 checks.push('分屏横向滑块可拖动且不占布局高度')

 await page.evaluate(()=>{const s=window.marqueeFixture.state;s.view='structure';s.structureLoading=false;s.structureText=Array.from({length:150},(_,i)=>`${i} ${'long-directory/'.repeat(30)}`).join('\n')})
 await frame()
 const pre=page.locator('.structure-text')
 assert(await pre.evaluate(el=>el.tagName==='PRE'&&el.scrollHeight>el.clientHeight&&el.scrollWidth>el.clientWidth),'目录结构未保留双向滚动')
 await page.evaluate(()=>window.marqueeFixture.state.structureText='short')
 await frame()
 assert(await pre.locator(':scope>.os-scrollbar').count()===2,'文本更新后滚动条丢失')
 await page.waitForFunction(()=>[...document.querySelectorAll('.structure-text>.os-scrollbar')].every(el=>getComputedStyle(el).opacity==='0'))
 await page.evaluate(()=>window.marqueeFixture.state.structureText=Array(200).fill('long '.repeat(100)).join('\n'));await frame()
 await pre.evaluate(el=>{el.scrollTop=100;el.scrollLeft=100})
 assert(await pre.evaluate(el=>el.scrollTop>0&&el.scrollLeft>0),'文本再次溢出后滚动失效')
 checks.push('pre 双向滚动、文本替换后滑块保留、无溢出隐藏及再次溢出恢复')

 await page.evaluate(()=>window.marqueeFixture.state.view='files');await frame()
 await page.evaluate(()=>{const s=window.marqueeFixture.state;for(let i=0;i<50;i++)s.recentDirectories.record('/recent/'+i)})
 await frame();await page.getByRole('button',{name:'最近访问目录',exact:true}).click()
 const recent=page.locator('.recent-list')
 assert(await recent.evaluate(el=>el.tagName==='UL'&&el.offsetWidth===el.clientWidth&&el.scrollHeight>el.clientHeight),'最近目录列表未采用悬浮滚动')
 await recent.evaluate(el=>el.scrollTop=150);await frame()
 assert(await recent.evaluate(el=>el.scrollTop===150),'最近目录不能滚动')
 await page.getByRole('button',{name:'关闭最近目录',exact:true}).click()
 await page.getByRole('button',{name:'最近访问目录',exact:true}).click()
 assert(await recent.locator(':scope>.os-scrollbar').count()===2,'浮层重建后滚动条数量异常')
 checks.push('ul 列表零占位、滚动及浮层销毁/重建')

 await page.goto(origin+'/tests/operation-paths.html')
 await page.waitForFunction(()=>document.title.startsWith('PASS'))
 const dialog=page.locator('.operation-dialog')
 assert(await dialog.evaluate(el=>el.open&&el.offsetWidth-el.clientWidth===2&&el.scrollHeight>el.clientHeight),'弹窗滚动占位或高度限制失效')
 await dialog.evaluate(el=>el.scrollTop=100);await frame()
 assert(await dialog.evaluate(el=>el.scrollTop>0),'弹窗不能滚动')
 checks.push('dialog 保留原生弹窗行为、边框、零滚动条占位及高度限制')

 await page.goto(origin+'/tests/marquee-selection.html')
 await page.waitForFunction(()=>window.marqueeFixture)
 await page.evaluate(async()=>{
  const {createApp,h}=await import('/node_modules/.vite/deps/vue.js')
  const {default:AppSelect}=await import('/src/components/AppSelect.vue')
  const host=document.createElement('div')
  host.style.cssText='position:fixed;top:200px;left:350px;width:200px'
  document.body.append(host)
  createApp({render:()=>h(AppSelect,{modelValue:'v0',options:Array.from({length:40},(_,i)=>({value:'v'+i,label:'Option '+i})),'onUpdate:modelValue':value=>{window.scrollbarSelection=value}})}).mount(host)
 })
 const select=page.getByRole('combobox')
 await select.click();await frame()
 const menu=page.locator('.app-select-menu')
 assert(await menu.evaluate(el=>el.offsetWidth-el.clientWidth===2&&el.scrollHeight>el.clientHeight),'下拉菜单未采用零占位滚动条')
 await select.press('End');await frame()
 assert(await menu.evaluate(el=>el.scrollTop>0),'菜单键盘定位没有滚动')
 await select.press('Enter')
 assert(await page.evaluate(()=>window.scrollbarSelection==='v39'),'菜单键盘选择失效')
 checks.push('长下拉菜单零占位、End 定位及 Enter 选择')
 return {passed:true,checks}
}

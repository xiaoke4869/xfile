// Run with a Playwright Page and Vite; uses the simulated Wails filesystem.
export default async function(page,origin='http://127.0.0.1:5173'){
 const assert=(condition,message)=>{if(!condition)throw new Error(message)}
 const near=(actual,expected,message)=>assert(Math.abs(actual-expected)<2,`${message}: ${actual} / ${expected}`)
 const frame=()=>page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))
 const widths=()=>page.locator('.file-panel').evaluateAll(elements=>elements.map(el=>el.getBoundingClientRect().width))
 const split=()=>page.getByRole('button',{name:'分屏',exact:true}).click()
 const fresh=async(count,width=3200)=>{
  await page.setViewportSize({width,height:860})
  await page.goto(origin+'/tests/file-drag.html')
  await page.waitForFunction(()=>window.dragFixture?.state.path==='/drag')
  await page.evaluate(()=>window.dragFixture.compact())
  for(let i=1;i<count;i++)await split()
  await page.locator('.browser-content').evaluate(el=>el.scrollLeft=0)
  await frame()
 }
 const drag=async(index,delta)=>{
  const separator=page.locator('.pane-resizer').nth(index)
  await separator.scrollIntoViewIfNeeded()
  const bounds=await separator.boundingBox(),x=bounds.x+bounds.width/2,y=bounds.y+120
  await page.mouse.move(x,y);await page.mouse.down()
  await page.mouse.move(x+delta,y+80,{steps:8});await frame()
  await page.mouse.up();await frame()
 }
 const checks=[]
 for(let count=2;count<=5;count++){
  await fresh(count)
  assert(await page.locator('.pane-resizer').count()===count-1,'分隔线数量错误')
  const before=await widths(),index=count-2
  await drag(index,60)
  const after=await widths()
  near(after[index],before[index]+60,`${count} 屏左屏未变宽`)
  near(after[index+1],before[index+1]-60,`${count} 屏右屏未变窄`)
  for(let i=0;i<index;i++)near(after[i],before[i],'其他屏被改变')
  assert(!await page.locator('.pane-resizing').count(),'松手后调整状态残留')
  const state=await page.evaluate(()=>({request:window.dragFixture.request,selected:window.dragFixture.state.panes.map(p=>p.selected.length)}))
  assert(!state.request&&state.selected.every(count=>count===0),'调整触发文件操作或选择')
 }
 checks.push('2–5 屏拖出分隔线持续调整、只改变相邻两屏、总宽守恒且不触发文件操作')
 await fresh(2,1600)
 await drag(0,600)
 near((await widths())[1],480,'右屏最小宽度限制失败')
 await drag(0,-900)
 near((await widths())[0],480,'左屏最小宽度限制失败')
 await page.locator('.pane-resizer').focus();await page.keyboard.press('ArrowRight');await frame()
 near((await widths())[0],496,'键盘调整失败')
 await page.keyboard.press('End');await frame();near((await widths())[1],480,'End 限制失败')
 await page.keyboard.press('Home');await frame();near((await widths())[0],480,'Home 限制失败')
 await page.setViewportSize({width:1000,height:860});await frame()
 assert((await widths()).every(width=>width>=480),'窄窗口违反最小宽度')
 assert(await page.locator('.browser-content').evaluate(el=>el.scrollWidth>el.clientWidth),'窄窗口缺少横向滚动')
 const minimum=await widths();await drag(0,100)
 ;(await widths()).forEach((width,i)=>near(width,minimum[i],'最小宽度双屏发生变化'))
 checks.push('左右最小宽度、键盘方向/Home/End、窄窗口横向滚动及双屏最小宽度边界')
 await fresh(3)
 await drag(0,100)
 const saved=await widths()
 await page.evaluate(async()=>{const s=window.dragFixture.state;await s.refreshPane(s.panes[0])});await frame()
 ;(await widths()).forEach((width,i)=>near(width,saved[i],'刷新丢失宽度'))
 await split()
 let current=await widths();current.forEach(width=>near(width,current[0],'新增后未均分'))
 await drag(0,60)
 await page.getByRole('button',{name:'关闭分屏 4',exact:true}).click();await frame()
 current=await widths();current.forEach(width=>near(width,current[0],'关闭后未均分'))
 while(await page.locator('.file-panel').count()>1)await page.getByRole('button',{name:'关闭分屏 1',exact:true}).click()
 await frame()
 assert(await page.locator('.pane-resizer').count()===0,'单屏残留分隔线')
 near((await widths())[0],await page.locator('.browser-content').evaluate(el=>el.clientWidth),'单屏未铺满')
 checks.push('刷新保持宽度、新增/关闭重新均分、单屏移除分隔线并铺满')
 await fresh(2,1800)
 for(const cancel of ['pointercancel','lostpointercapture','blur','Escape']){
  const bounds=await page.locator('.pane-resizer').boundingBox()
  await page.mouse.move(bounds.x+3,bounds.y+120);await page.mouse.down()
  await page.mouse.move(bounds.x+33,bounds.y+120);await frame()
  if(cancel==='Escape')await page.keyboard.press('Escape')
  else await page.evaluate(cancel=>{
   if(cancel==='blur')window.dispatchEvent(new FocusEvent('blur'))
   else{
    const element=document.querySelector('.pane-resizer'),pointerId=window.dragFixture.state.paneDrag.pointerId
    if(cancel==='lostpointercapture')element.releasePointerCapture(pointerId)
    else element.dispatchEvent(new PointerEvent('pointercancel',{pointerId}))
   }
  },cancel)
  // Browsers deliver lostpointercapture while processing the next pointer event.
  if(cancel==='lostpointercapture')await page.mouse.move(bounds.x+33,bounds.y+120)
  await frame()
  assert(!await page.locator('.pane-resizing').count(),`${cancel} 未结束调整`)
  const stopped=await widths()
  await page.mouse.move(bounds.x+63,bounds.y+120);await page.mouse.up();await frame()
  ;(await widths()).forEach((width,i)=>near(width,stopped[i],`${cancel} 后仍在调整`))
 }
 const proportion=(await widths())[0]/(await widths())[1]
 await page.setViewportSize({width:2200,height:860});await frame()
 const expanded=await widths()
 assert(Math.abs(expanded[0]/expanded[1]-proportion)<.01,'窗口变宽丢失比例')
 near(expanded.reduce((a,b)=>a+b,6),await page.locator('.browser-content').evaluate(el=>el.clientWidth),'窗口变宽未铺满')
 checks.push('取消、失去指针捕获、窗口失焦、Esc 清理与窗口宽度适配')
 await fresh(2,1800)
 await drag(0,80)
 await page.evaluate(async()=>{const s=window.dragFixture.state;await s.navigate('/drag/00-target',true,true,s.panes[1])})
 await frame()
 const source=page.locator('.file-panel').first().locator('.file-label[title="/drag/10-a.txt"]')
 let bounds=await source.boundingBox()
 await page.mouse.move(bounds.x+10,bounds.y+bounds.height/2);await page.mouse.down()
 const line=await page.locator('.pane-resizer').boundingBox()
 await page.mouse.move(line.x+line.width/2,line.y+160,{steps:8});await frame()
 assert(!await page.locator('.drop-current-directory,.drop-group,.drop-folder').count(),'分隔线错误接受文件落点')
 await page.mouse.up();await frame()
 assert(!await page.evaluate(()=>window.dragFixture.request),'向分隔线松手执行了文件操作')
 bounds=await source.boundingBox()
 await page.mouse.move(bounds.x+10,bounds.y+bounds.height/2);await page.mouse.down()
 const target=await page.locator('.file-panel').nth(1).locator('.table-scroll').boundingBox()
 await page.mouse.move(target.x+target.width*.7,target.y+target.height-50,{steps:10});await frame()
 assert(await page.locator('.drop-current-directory').count()===1,'调整宽度后跨屏落点失败')
 await page.mouse.up();await frame()
 const request=await page.evaluate(()=>{const r=window.dragFixture.request;return r&&{name:r.name,args:r.args,paths:r.paths}})
 assert(request?.name==='TransferEntries'&&request.paths.includes('/drag/10-a.txt')&&request.args.includes('/drag/00-target'),'调整后跨屏移动参数错误')
 await page.evaluate(()=>window.dragFixture.finish());await frame()
 checks.push('调整后文件拖到分隔线不执行操作、跨屏当前目录移动正确')
 return checks
}
